-- p_action: dismiss | require_change | hide | restore
--   dismiss         close open reports; a name hidden by the automated screen is shown again
--   require_change  owner must pick a new name; the current one stays visible until then
--   hide            confirmed abusive: replaced by a neutral placeholder now, owner must pick
--                   a new name, and the name (and look-alikes) can never be claimed again
--   restore         undo a hide or required change
create function public.admin_moderate_name(p_target_ref uuid, p_action text, p_note text default null)
returns jsonb language plpgsql volatile security definer set search_path = '' as $$
declare me uuid := public.rr_require_admin(); tgt public.profiles; ids bigint[]; nm text; key text;
begin
  if p_action not in ('dismiss', 'require_change', 'hide', 'restore') then raise exception 'Unknown action'; end if;
  select * into tgt from public.profiles where public_ref = p_target_ref for update;
  if not found then return jsonb_build_object('status', 'not_found'); end if;
  nm := coalesce(tgt.username, tgt.display_name);
  key := public.rr_username_skeleton(regexp_replace(coalesce(nm, ''), '[^A-Za-z0-9_]', '', 'g'));

  with closed as (
    update public.username_reports
       set status = case when p_action in ('dismiss', 'restore') then 'dismissed' else 'actioned' end,
           reviewed_by = me, reviewed_at = now(), resolution = p_action
     where target_user_id = tgt.id and status = 'open'
    returning id)
  select array_agg(id order by id) into ids from closed;

  if p_action = 'dismiss' then
    if tgt.name_state = 'hidden' and tgt.name_state_reason = 'automated' then
      update public.profiles set name_state = 'ok', name_state_reason = null where id = tgt.id;
    end if;
  elsif p_action = 'require_change' then
    if tgt.name_state <> 'hidden' then
      update public.profiles set name_state = 'change_required', name_state_reason = 'admin' where id = tgt.id;
    end if;
  elsif p_action = 'hide' then
    update public.profiles set name_state = 'hidden', name_state_reason = 'admin' where id = tgt.id;
    if key <> '' then
      insert into public.username_blocked_names (name_key, blocked_by) values (key, me) on conflict do nothing;
    end if;
  elsif p_action = 'restore' then
    update public.profiles set name_state = 'ok', name_state_reason = null where id = tgt.id;
    delete from public.username_blocked_names where name_key = key;
  end if;

  insert into public.moderation_audit (actor_id, action, target_user_id, report_ids, detail)
  values (me, 'admin_' || p_action, tgt.id, ids,
          jsonb_build_object('name', nm, 'previous_state', tgt.name_state, 'note', nullif(btrim(coalesce(p_note, '')), '')));
  return jsonb_build_object('status', 'ok', 'closed_reports', coalesce(array_length(ids, 1), 0));
end $$;

-- Approve: the name becomes allowed and is given to the requester if still free.
create function public.admin_resolve_review(p_id bigint, p_approve boolean, p_note text default null)
returns jsonb language plpgsql volatile security definer set search_path = '' as $$
declare me uuid := public.rr_require_admin(); q public.username_review_requests; res jsonb := '{}'::jsonb;
begin
  select * into q from public.username_review_requests where id = p_id for update;
  if not found or q.status <> 'open' then return jsonb_build_object('status', 'not_open'); end if;
  if p_approve then
    insert into public.username_allowed_names (name_key, approved_by) values (lower(q.requested_name), me)
    on conflict (name_key) do update set approved_by = me, approved_at = now();
    delete from public.username_blocked_names where name_key = public.rr_username_skeleton(q.requested_name);
    res := public.rr_apply_username(q.user_id, q.requested_name, false, me);
  end if;
  update public.username_review_requests
     set status = case when p_approve then 'approved' else 'denied' end,
         reviewed_by = me, reviewed_at = now(), resolution_note = nullif(btrim(coalesce(p_note, '')), '')
   where id = p_id;
  insert into public.moderation_audit (actor_id, action, target_user_id, appeal_id, detail)
  values (me, case when p_approve then 'admin_approve_review' else 'admin_deny_review' end, q.user_id, p_id,
          jsonb_build_object('name', q.requested_name, 'assigned', res->>'status', 'note', nullif(btrim(coalesce(p_note, '')), '')));
  return jsonb_build_object('status', 'ok', 'assigned', coalesce(res->>'status', 'no'));
end $$;

-- Why does (or doesn't) a name pass? Admin troubleshooting only.
create function public.admin_test_username(p_name text)
returns table (format_ok boolean, category text, term text, rule text, variant text, allowed boolean, blocked boolean, available boolean)
language plpgsql stable security definer set search_path = '' as $$
begin
  perform public.rr_require_admin();
  return query
  select public.rr_username_format_ok(p_name),
         coalesce(m.category, public.rr_username_digit_problem(p_name)), m.term, m.rule, m.variant,
         exists (select 1 from public.username_allowed_names a where a.name_key = lower(p_name)),
         exists (select 1 from public.username_blocked_names b where b.name_key = public.rr_username_skeleton(p_name)),
         not public.rr_username_taken(p_name, null)
  from (select 1) one left join lateral (select * from public.rr_username_match(p_name) limit 1) m on true;
end $$;

create function public.admin_add_term(p_term text, p_category text, p_match text, p_note text default null)
returns jsonb language plpgsql volatile security definer set search_path = '' as $$
declare me uuid := public.rr_require_admin(); t text := lower(btrim(coalesce(p_term, '')));
begin
  if p_match = 'regex' then
    t := btrim(p_term);
    begin perform '' ~ t; exception when others then return jsonb_build_object('status', 'invalid'); end;
  end if;
  insert into public.moderation_terms (term, category, match, source, note) values (t, p_category, p_match, 'admin', p_note)
  on conflict (term, match) do update set enabled = true, category = excluded.category;
  insert into public.moderation_audit (actor_id, action, detail)
  values (me, 'admin_add_term', jsonb_build_object('match', p_match, 'category', p_category));  -- the term itself stays out of the log
  return jsonb_build_object('status', 'ok');
exception when check_violation then
  return jsonb_build_object('status', 'invalid');
end $$;

