-- Defense in depth: even if a grant is widened later, API roles can't touch
-- name columns. SECURITY DEFINER functions run as the owner and pass.
create function public.rr_profiles_guard()
returns trigger language plpgsql set search_path = '' as $$
begin
  if current_user in ('anon', 'authenticated') then
    if tg_op = 'INSERT' then
      if new.username is not null or new.display_name is not null or new.name_state <> 'ok'
         or new.name_state_reason is not null or new.username_set_at is not null or new.username_changed_at is not null then
        raise exception 'Choose a nickname through set_username' using errcode = '42501';
      end if;
      new.public_ref := gen_random_uuid();
    elsif (new.id, new.username, new.display_name, new.name_state, new.name_state_reason,
           new.username_set_at, new.username_changed_at, new.public_ref)
          is distinct from
          (old.id, old.username, old.display_name, old.name_state, old.name_state_reason,
           old.username_set_at, old.username_changed_at, old.public_ref) then
      raise exception 'Choose a nickname through set_username' using errcode = '42501';
    end if;
  end if;
  return new;
end $$;
create trigger rr_profiles_guard before insert or update on public.profiles
  for each row execute function public.rr_profiles_guard();

