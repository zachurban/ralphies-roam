create function public.admin_list_terms()
returns table (id bigint, term text, category text, match text, source text, enabled boolean, note text)
language plpgsql stable security definer set search_path = '' as $$
begin
  perform public.rr_require_admin();
  return query select t.id, t.term, t.category, t.match, t.source, t.enabled, t.note
               from public.moderation_terms t where t.source <> 'ldnoobw' order by t.source, t.category, t.term;
end $$;

-- After changing the policy: queue (never hide) every public name that now fails.
create function public.admin_rescan_names()
returns jsonb language plpgsql volatile security definer set search_path = '' as $$
declare me uuid := public.rr_require_admin(); n int := 0; pr record;
begin
  for pr in select * from public.profiles where name_state = 'ok' and coalesce(username, display_name) is not null loop
    if public.rr_username_problem(coalesce(pr.username, pr.display_name)) is not null
       or public.rr_username_digit_problem(coalesce(pr.username, pr.display_name)) is not null then
      insert into public.username_reports (target_user_id, source, reported_name, reason)
      values (pr.id, 'automated', coalesce(pr.username, pr.display_name), 'automated')
      on conflict do nothing;
      if found then n := n + 1; end if;
    end if;
  end loop;
  insert into public.moderation_audit (actor_id, action, detail) values (me, 'admin_rescan', jsonb_build_object('queued', n));
  return jsonb_build_object('status', 'ok', 'queued', n);
end $$;

create function public.admin_audit_log(p_limit int default 100)
returns table (id bigint, at timestamptz, actor_ref uuid, action text, target_ref uuid, report_ids bigint[], appeal_id bigint, detail jsonb)
language plpgsql stable security definer set search_path = '' as $$
begin
  perform public.rr_require_admin();
  return query
  select a.id, a.at, pa.public_ref, a.action, pt.public_ref, a.report_ids, a.appeal_id, a.detail
  from public.moderation_audit a
  left join public.profiles pa on pa.id = a.actor_id
  left join public.profiles pt on pt.id = a.target_user_id
  order by a.at desc, a.id desc
  limit least(greatest(p_limit, 1), 500);
end $$;

