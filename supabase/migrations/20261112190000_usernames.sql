-- Is the name (or a look-alike) held by someone other than p_uid?
create function public.rr_username_taken(p text, p_uid uuid)
returns boolean language sql stable security definer set search_path = '' as $$
  select exists (select 1 from public.profiles
                 where id is distinct from p_uid
                   and (lower(username) = lower(p) or username_skeleton = public.rr_username_skeleton(p)))
      or exists (select 1 from public.released_usernames
                 where name_key = public.rr_username_skeleton(p)
                   and released_by is distinct from p_uid
                   and released_at > now() - interval '30 days');
$$;

-- Applies a name that has already passed format + moderation. Atomic via the unique indexes.
create function public.rr_apply_username(p_uid uuid, p_name text, p_enforce_limit boolean, p_actor uuid)
returns jsonb language plpgsql volatile security definer set search_path = '' as $$
declare pr public.profiles; next_at timestamptz;
begin
  if not public.rr_username_format_ok(p_name) then return jsonb_build_object('status', 'format'); end if;
  insert into public.profiles (id) values (p_uid) on conflict (id) do nothing;
  select * into pr from public.profiles where id = p_uid for update;

  if pr.username = p_name and pr.name_state = 'ok' then
    return jsonb_build_object('status', 'ok', 'name', p_name, 'unchanged', true);
  end if;
  -- A moderator asked for a different name: the same name (or a look-alike) doesn't count.
  if p_enforce_limit and pr.name_state <> 'ok'
     and public.rr_username_skeleton(p_name) = public.rr_username_skeleton(regexp_replace(coalesce(pr.username, pr.display_name, ''), '[^A-Za-z0-9_]', '', 'g')) then
    return jsonb_build_object('status', 'guidelines');
  end if;
  -- Change limit: one change per 7 days once a name is set. The first pick, a
  -- capitalization-only edit, and a change an administrator required are free.
  if p_enforce_limit and pr.username is not null and pr.name_state = 'ok'
     and lower(pr.username) <> lower(p_name)
     and pr.username_changed_at is not null and pr.username_changed_at > now() - interval '7 days' then
    next_at := pr.username_changed_at + interval '7 days';
    return jsonb_build_object('status', 'too_soon', 'next_at', next_at);
  end if;
  if public.rr_username_taken(p_name, p_uid) then return jsonb_build_object('status', 'taken'); end if;

  begin
    update public.profiles
       set username = p_name,
           username_set_at = coalesce(username_set_at, now()),
           username_changed_at = case when pr.username is null or lower(pr.username) = lower(p_name)
                                      then username_changed_at else now() end,
           name_state = 'ok', name_state_reason = null
     where id = p_uid;
  exception when unique_violation then
    return jsonb_build_object('status', 'taken');
  end;

  if pr.username is not null and pr.username_skeleton <> public.rr_username_skeleton(p_name) and pr.name_state <> 'hidden' then
    insert into public.released_usernames (name_key, released_by, released_at)
    values (pr.username_skeleton, p_uid, now())
    on conflict (name_key) do update set released_by = excluded.released_by, released_at = now();
  end if;
  delete from public.released_usernames where name_key = public.rr_username_skeleton(p_name) and released_by = p_uid;

  insert into public.moderation_audit (actor_id, action, target_user_id, detail)
  values (p_actor, case when p_actor = p_uid then 'user_set_username' else 'admin_set_username' end, p_uid,
          jsonb_build_object('old', coalesce(pr.username, pr.display_name), 'new', p_name, 'previous_state', pr.name_state));
  return jsonb_build_object('status', 'ok', 'name', p_name);
end $$;

-- Advisory check while typing. Statuses: ok | current | format | guidelines | taken | rate_limited
create function public.check_username(p_name text)
returns jsonb language plpgsql volatile security definer set search_path = '' as $$
declare uid uuid := auth.uid(); cur text;
begin
  if uid is null then raise exception 'Sign in first' using errcode = '42501'; end if;
  if not public.rr_rate_ok('username_check', 60, interval '10 minutes') then return jsonb_build_object('status', 'rate_limited'); end if;
  if not public.rr_username_format_ok(p_name) then return jsonb_build_object('status', 'format'); end if;
  select username into cur from public.profiles where id = uid;
  if cur = p_name then return jsonb_build_object('status', 'current'); end if;
  if public.rr_username_problem(p_name) is not null or public.rr_username_digit_problem(p_name) is not null then
    return jsonb_build_object('status', 'guidelines');
  end if;
  if public.rr_username_taken(p_name, uid) then return jsonb_build_object('status', 'taken'); end if;
  return jsonb_build_object('status', 'ok');
end $$;

-- A random campus nickname, generated from the curated lists only (never from
-- account data), screened, and currently available.
create function public.suggest_username()
returns jsonb language plpgsql volatile security definer set search_path = '' as $$
declare uid uuid := auth.uid(); refs text[] := public.rr_name_refs(); words text[] := public.rr_name_words();
        r text; w text; d text; cand text; i int;
begin
  if uid is null then raise exception 'Sign in first' using errcode = '42501'; end if;
  if not public.rr_rate_ok('username_suggest', 60, interval '10 minutes') then return jsonb_build_object('status', 'rate_limited'); end if;
  for i in 1..40 loop
    r := refs[1 + floor(random() * array_length(refs, 1))::int];
    w := words[1 + floor(random() * array_length(words, 1))::int];
    continue when lower(r) = lower(w);
    if random() < 0.85 then
      d := (100 + floor(random() * 900))::int::text;
      continue when d ~ '(69|420|666|911|187|88|13)';
    else d := ''; end if;
    cand := r || w || d;
    continue when not public.rr_username_format_ok(cand);
    continue when public.rr_username_problem(cand) is not null or public.rr_username_digit_problem(cand) is not null;
    continue when public.rr_username_taken(cand, uid);
    return jsonb_build_object('status', 'ok', 'name', cand);
  end loop;
  return jsonb_build_object('status', 'unavailable');
end $$;

-- Save a nickname. Statuses: ok | format | guidelines | taken | too_soon (+next_at) | rate_limited
create function public.set_username(p_name text)
returns jsonb language plpgsql volatile security definer set search_path = '' as $$
declare uid uuid := auth.uid();
begin
  if uid is null then raise exception 'Sign in first' using errcode = '42501'; end if;
  if not public.rr_rate_ok('username_set', 10, interval '1 hour') then return jsonb_build_object('status', 'rate_limited'); end if;
  if not public.rr_username_format_ok(p_name) then return jsonb_build_object('status', 'format'); end if;
  if public.rr_username_problem(p_name) is not null or public.rr_username_digit_problem(p_name) is not null then
    return jsonb_build_object('status', 'guidelines');
  end if;
  return public.rr_apply_username(uid, p_name, true, uid);
end $$;

