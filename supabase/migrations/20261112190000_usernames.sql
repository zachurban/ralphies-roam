-- Report a public name by its opaque ref. Reports never hide a name by
-- themselves, however many there are: only an administrator can.
-- Statuses: ok | already_reported | not_found | self | invalid | rate_limited
create function public.report_username(p_ref uuid, p_reason text, p_note text default null)
returns jsonb language plpgsql volatile security definer set search_path = '' as $$
declare uid uuid := auth.uid(); tgt public.profiles;
begin
  if uid is null then raise exception 'Sign in first' using errcode = '42501'; end if;
  if p_reason is null or p_reason not in ('profanity', 'hate', 'sexual', 'threat', 'harassment', 'accusation',
                                          'impersonation', 'personal_info', 'other')
     or char_length(coalesce(p_note, '')) > 280 then
    return jsonb_build_object('status', 'invalid');
  end if;
  select * into tgt from public.profiles where public_ref = p_ref;
  if not found then return jsonb_build_object('status', 'not_found'); end if;
  if tgt.id = uid then return jsonb_build_object('status', 'self'); end if;
  if exists (select 1 from public.username_reports where target_user_id = tgt.id and reporter_id = uid and status = 'open') then
    return jsonb_build_object('status', 'already_reported');
  end if;
  if not public.rr_rate_ok('username_report', 10, interval '1 day') then return jsonb_build_object('status', 'rate_limited'); end if;
  insert into public.username_reports (target_user_id, reporter_id, reported_name, reason, note)
  values (tgt.id, uid, public.rr_public_name(tgt.id, tgt.username, tgt.display_name, tgt.name_state), p_reason,
          nullif(btrim(coalesce(p_note, '')), ''));
  return jsonb_build_object('status', 'ok');
exception when unique_violation then
  return jsonb_build_object('status', 'already_reported');
end $$;

