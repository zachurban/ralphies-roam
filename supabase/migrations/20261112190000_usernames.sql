-- BuffPrints — public nicknames (usernames), server-side moderation, reports,
-- review requests and an administrator queue.
--
-- Design rules
--   * profiles.id (= auth.users.id) stays the identity for every relationship.
--     A username is a display value only; nothing references it.
--   * Every username write goes through set_username() (or an admin function).
--     Direct table writes to name columns are refused by column privileges AND a
--     trigger, so the REST API can't skip moderation.
--   * Uniqueness is enforced by unique indexes (case-insensitive, plus a
--     look-alike "skeleton"), so simultaneous claims can't both succeed.
--   * Moderation lists, admin tables, reports and the audit trail have RLS on and
--     no grants: only SECURITY DEFINER functions in this file read them.
--   * Public error statuses never reveal which term or rule matched.
--
-- Companion migrations: *_moderation_baseline_ldnoobw.sql (maintained word
-- list, generated by scripts/build-moderation-terms.mjs) and
-- *_username_legacy.sql (screens existing leaderboard names).

------------------------------------------------------------------------------
-- 1. Profile columns
------------------------------------------------------------------------------
-- Look-alike key: case-folded, underscores dropped, 0→o, 1/i→l.
-- "Zach_Urban", "zachurban" and "ZachUrbaN" share one; so do "Norlin" and "Nor1in".
create function public.rr_username_skeleton(p text)
returns text language sql immutable parallel safe set search_path = '' as $$
  select translate(replace(lower(p), '_', ''), '01i', 'oll');
$$;

-- 3–24 ASCII letters, digits or underscores, at least one letter. Nothing is
-- trimmed or rewritten: a name that isn't already valid is rejected.
create function public.rr_username_format_ok(p text)
returns boolean language sql immutable parallel safe set search_path = '' as $$
  select p is not null
     and octet_length(p) = char_length(p)            -- ASCII only (no lookalike or invisible Unicode)
     and p ~ '^[A-Za-z0-9_]{3,24}$'
     and p ~ '[A-Za-z]';
$$;

alter table public.profiles
  add column username            text check (username is null or public.rr_username_format_ok(username)),
  add column username_skeleton   text generated always as (public.rr_username_skeleton(username)) stored,
  add column username_set_at     timestamptz,   -- first time a nickname was chosen
  add column username_changed_at timestamptz,   -- last user-initiated change (drives the change limit)
  add column name_state          text not null default 'ok'
                                 check (name_state in ('ok', 'change_required', 'hidden')),
  add column name_state_reason   text check (name_state_reason in ('automated', 'admin')),
  add column public_ref          uuid not null default gen_random_uuid();  -- opaque handle for reporting; not the account id

create unique index profiles_username_lower_key    on public.profiles (lower(username));
create unique index profiles_username_skeleton_key on public.profiles (username_skeleton);
create unique index profiles_public_ref_key        on public.profiles (public_ref);

-- The one place that decides what other students see. Never an email or legal
-- name: a missing or hidden name becomes a neutral "Buff 1A2B" placeholder
-- (from the random account id, which has no personal meaning).
create function public.rr_public_name(p_id uuid, p_username text, p_display_name text, p_state text)
returns text language sql immutable parallel safe set search_path = '' as $$
  select case
    when p_state = 'hidden'          then 'Buff ' || upper(left(p_id::text, 4))
    when p_username is not null      then p_username
    when p_display_name is not null  then p_display_name      -- legacy name, screened by *_username_legacy.sql
    else 'Buff ' || upper(left(p_id::text, 4))
  end;
$$;

