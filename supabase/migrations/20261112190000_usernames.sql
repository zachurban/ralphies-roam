-- Moderation policy. match:
--   substring  anywhere in the joined letters (after leet/separator variants)
--   token      a whole word (camelCase, underscores and digits split words), or the whole name
--   edge       the start or end of a word, or the whole name
--   phrase     consecutive words ("blow job"), or the whole name with words joined
--   regex      a regular expression run on the joined letters
-- Letters may be stretched ("fuuuck") for every mode except regex.
create table public.moderation_terms (
  id         bigint generated always as identity primary key,
  term       text not null check (char_length(term) between 2 and 1000),
  category   text not null check (category in ('profanity', 'slur', 'sexual', 'violence', 'self_harm', 'harassment',
                                                'accusation', 'impersonation', 'personal_info', 'spam')),
  match      text not null check (match in ('substring', 'token', 'edge', 'phrase', 'regex')),
  source     text not null default 'app' check (source in ('app', 'ldnoobw', 'admin')),
  enabled    boolean not null default true,
  note       text,
  created_at timestamptz not null default now(),
  check (match = 'regex' or term ~ '^[a-z]+( [a-z]+)*$'),
  unique (term, match)
);

-- Reviewed exceptions (the Scunthorpe problem). kind:
--   token    masks the word only inside a single word, so "Therapist" passes but
--            "TheRapist" / "the_rapist" are still checked
--   phrase   masks a word sequence ("summa cum laude")
--   compact  masks it in the joined letters, also across word breaks ("WashItUp")
create table public.moderation_exceptions (
  id         bigint generated always as identity primary key,
  word       text not null check (word ~ '^[a-z]+( [a-z]+)*$' and char_length(word) between 3 and 60),
  kind       text not null check (kind in ('token', 'phrase', 'compact')),
  enabled    boolean not null default true,
  note       text,
  created_at timestamptz not null default now(),
  unique (word, kind)
);

