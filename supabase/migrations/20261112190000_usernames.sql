-- Regex that matches a term with stretched letters: 'boob' -> 'b+o{2,}b+'.
create function public.rr_stretch(p text)
returns text language plpgsql immutable parallel safe set search_path = '' as $$
declare out text := ''; i int := 1; c text; n int;
begin
  while i <= char_length(p) loop
    c := substr(p, i, 1); n := 1;
    while substr(p, i + n, 1) = c loop n := n + 1; end loop;
    if c = ' ' then out := out || ' ';
    elsif n = 1 then out := out || c || '+';
    else out := out || c || '{' || n || ',}';
    end if;
    i := i + n;
  end loop;
  return out;
end $$;

alter table public.moderation_terms
  add column pattern text generated always as (case when match = 'regex' then term else public.rr_stretch(term) end) stored;

-- Several normalized views of one name. Each is lowercase words separated by
-- single spaces. Nothing here changes the stored name.
--   word splits: camelCase ("FlatironFox"), acronyms, underscores, punctuation
--   digits: as word breaks ("Fox482"), or as letters (0→o 1→i|l 3→e 4→a 5→s 7→t 8→b 9→g)
--   with and without camelCase splitting, so odd capitals ("MyAsS") don't hide words
create function public.rr_mod_variants(p text)
returns text[] language plpgsql immutable parallel safe set search_path = '' as $$
declare camel text; plain text; base text; out text[] := '{}'; v text;
begin
  camel := regexp_replace(coalesce(p, ''), '([A-Z])(?=[A-Z][a-z])', '\1 ', 'g');
  camel := regexp_replace(camel, '([a-z0-9])(?=[A-Z][a-z])', '\1 ', 'g');
  camel := lower(camel);
  plain := lower(coalesce(p, ''));
  foreach base in array array[camel, plain] loop
    foreach v in array array[
      regexp_replace(base, '[0-9]+', ' ', 'g'),
      translate(base, '013456789@$!', 'oieasgtbgasi'),
      translate(base, '013456789@$!', 'oleasgtbgasl')
    ] loop
      v := btrim(regexp_replace(regexp_replace(v, '[^a-z]+', ' ', 'g'), ' +', ' ', 'g'));
      if v <> '' and not v = any(out) then out := out || v; end if;
    end loop;
  end loop;
  return out;
end $$;

-- Full match detail. Internal: exposed to administrators only (admin_test_username).
-- Each match mode is compiled into one alternation regex per call, so a check
-- costs a handful of regex evaluations instead of one per term.
create function public.rr_username_match(p text)
returns table (category text, term text, rule text, variant text)
language plpgsql stable security definer set search_path = '' as $$
declare
  v text; compact text; toks text[]; tok text; t record; hit text; ok boolean;
  tok_ex text[]; phr_ex text[]; cmp_ex text[];
  re_sub text; re_tok text; re_edge text; re_phr text; re_phrc text; re_rx text;
begin
  if coalesce(p, '') ~ '[0-9]{7,}' then
    return query select 'personal_info'::text, '7+ digits'::text, 'digits'::text, p; return;
  end if;
  select coalesce(array_agg(word) filter (where kind = 'token'), '{}'),
         coalesce(array_agg(word) filter (where kind = 'phrase'), '{}'),
         coalesce(array_agg(word) filter (where kind = 'compact'), '{}')
    into tok_ex, phr_ex, cmp_ex
  from public.moderation_exceptions where enabled;
  select '(' || string_agg(pattern, '|') filter (where match = 'substring') || ')',
         '^(' || string_agg(pattern, '|') filter (where match = 'token') || ')s?$',
         string_agg(pattern, '|') filter (where match = 'edge'),
         ' (' || string_agg(pattern, '|') filter (where match = 'phrase') || ') ',
         '^(' || string_agg(replace(pattern, ' ', ''), '|') filter (where match = 'phrase') || ')s?$',
         '(' || string_agg('(?:' || pattern || ')', '|') filter (where match = 'regex') || ')'
    into re_sub, re_tok, re_edge, re_phr, re_phrc, re_rx
  from public.moderation_terms where enabled;

  foreach v in array public.rr_mod_variants(p) loop
    -- reviewed exceptions: phrases, then words inside a single word, then joined letters
    foreach tok in array phr_ex loop v := regexp_replace(v, '(^| )' || tok || '( |$)', ' # ', 'g'); end loop;
    foreach tok in array tok_ex loop v := replace(v, tok, '#'); end loop;
    foreach tok in array cmp_ex loop v := replace(v, tok, '#'); end loop;   -- compact exceptions also apply inside a word
    v := btrim(regexp_replace(v, ' +', ' ', 'g'));
    toks := string_to_array(v, ' ');
    compact := replace(v, ' ', '');
    foreach tok in array cmp_ex loop compact := replace(compact, replace(tok, ' ', ''), '#'); end loop;

    hit := case
      when re_sub is not null and compact ~ re_sub then 'substring'
      when re_tok is not null and (compact ~ re_tok or exists (select 1 from unnest(toks) x where x ~ re_tok)) then 'token'
      when re_edge is not null and (compact ~ ('^(' || re_edge || ')s?$')
           or exists (select 1 from unnest(toks) x where x ~ ('^(' || re_edge || ')') or x ~ ('(' || re_edge || ')s?$'))) then 'edge'
      when re_phr is not null and ((' ' || v || ' ') ~ re_phr or compact ~ re_phrc) then 'phrase'
      when re_rx is not null and compact ~ re_rx then 'regex'
    end;
    if hit is null then continue; end if;

    -- identify the term (only on the rare hit path)
    for t in select mt.term, mt.category, mt.pattern from public.moderation_terms mt where mt.enabled and mt.match = hit order by mt.id loop
      ok := case hit
           when 'substring' then compact ~ t.pattern
           when 'token'     then compact ~ ('^' || t.pattern || 's?$') or exists (select 1 from unnest(toks) x where x ~ ('^' || t.pattern || 's?$'))
           when 'edge'      then compact ~ ('^' || t.pattern || 's?$') or exists (select 1 from unnest(toks) x where x ~ ('^' || t.pattern) or x ~ (t.pattern || 's?$'))
           when 'phrase'    then (' ' || v || ' ') ~ (' ' || t.pattern || ' ') or compact ~ ('^' || replace(t.pattern, ' ', '') || 's?$')
           else compact ~ t.pattern end;
      if ok then
        return query select t.category, t.term, hit, v; return;
      end if;
    end loop;
  end loop;
  return;
end $$;

-- NULL when the name is acceptable, otherwise a category (internal use only).
create function public.rr_username_problem(p text)
returns text language plpgsql stable security definer set search_path = '' as $$
declare c text;
begin
  if exists (select 1 from public.username_allowed_names where name_key = lower(p)) then return null; end if;
  if exists (select 1 from public.username_blocked_names where name_key = public.rr_username_skeleton(p)) then return 'blocked'; end if;
  select m.category into c from public.rr_username_match(p) m limit 1;
  return c;
end $$;

