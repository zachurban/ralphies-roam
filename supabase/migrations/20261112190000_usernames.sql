create function public.rr_rate_ok(p_action text, p_max int, p_window interval)
returns boolean language plpgsql volatile security definer set search_path = '' as $$
declare uid uuid := auth.uid(); n int;
begin
  if uid is null then return false; end if;
  delete from public.rate_events where user_id = uid and action = p_action
    and at < now() - greatest(p_window, interval '1 day');
  select count(*) into n from public.rate_events where user_id = uid and action = p_action and at > now() - p_window;
  if n >= p_max then return false; end if;
  insert into public.rate_events (user_id, action) values (uid, p_action);
  return true;
end $$;

